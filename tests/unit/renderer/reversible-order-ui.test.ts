import { describe, expect, it } from 'vitest'
import { readFileSync } from 'node:fs'

const source = (path: string) => readFileSync(`src/renderer/${path}`, 'utf8')
const orders = source('pages/orders/OrdersPage.tsx')
const detail = source('pages/orders/OrderDetailPage.tsx')
const manufacturing = source('components/orders/ManufacturingReversalButton.tsx')
const sheets = source('pages/worksheets/WorkSheetsPage.tsx')
const sheet = source('pages/worksheets/ProductionOrderPage.tsx')
const permits = source('pages/releases/ReleasesPage.tsx')
const invoice = source('pages/invoices/FinalInvoicesPage.tsx')
const delivery = source('pages/deliveries/DeliveriesPage.tsx')
const productionService = readFileSync('src/main/services/production/production.service.ts', 'utf8')

describe('domain-owned reversal Arabic RTL UI contracts', () => {
  it('CC01: locks Production Preparation read-only once manufacturing is completed, keeping every tab readable', () => {
    expect(detail).toContain("const manufacturingCompleted = worksheets.items.some((sheet) => sheet.status === 'completed')")
    expect(detail).toMatch(/const configEditable = [^\n]*&& !manufacturingCompleted/)
    expect(detail).toContain('? PRODUCTION_PREP_LOCKED_MESSAGE')
    expect(detail).toContain('actions={\n            (\n              <div className="tabs">')
    for (const saver of ['savePlannedMaterials', 'savePlannedMachines', 'savePlannedWorkers', 'savePlannedExpenses']) expect(detail).toContain(`'orders', '${saver}'`)
  })
  it('exposes Manufacturing Order undo from its own list and detail, never a centralized order-stage rollback', () => {
    expect(sheets).toContain('ManufacturingReversalButton')
    expect(sheet).toContain('ManufacturingReversalButton')
    expect(manufacturing).toContain("'production', 'reverseWorkSheet'")
    for (const page of [orders, detail, invoice]) {
      expect(page).not.toContain('rollbackWorkflow')
      expect(page).not.toContain('rollback-stage')
      expect(page).not.toContain('الرجوع إلى مرحلة سابقة')
    }
  })
  it('requires focused manufacturing authority, backend preview token, exact typed document number and a reason', () => {
    expect(manufacturing).toContain('sourceOrderArchived || manufacturingStarted(sheet) || !can(P.worksheets.reverse)')
    expect(manufacturing).toContain("'production', 'getWorkSheet'")
    expect(manufacturing).toContain('expectedToken: preview.reversalToken')
    expect(manufacturing).toContain('confirmation.trim() !== preview?.sheet.documentNumber')
    expect(manufacturing).toContain('!reason.trim()')
    expect(manufacturing).toContain('تحديث المعاينة')
    expect(manufacturing).toContain('دفعات العميل وفواتير الشراء')
    expect(manufacturing).toContain('لن يعكس النظام أي خطوة لاحقة تلقائياً')
  })
  it('hides Manufacturing Order reversal for archived source orders and pins the backend domain guard', () => {
    expect(manufacturing).toContain('sourceOrderArchived || manufacturingStarted(sheet) || !can(P.worksheets.reverse)')
    expect(sheets).toContain('sheet={row} sourceOrderArchived={Boolean(row.orderArchivedAt)}')
    expect(sheet).toContain('sheet={sheet} sourceOrderArchived={Boolean(data.order.archivedAt)}')
    expect(productionService).toContain('لا يمكن التراجع عن أمر تصنيع تابع لطلب مؤرشف')
    expect(productionService).toContain('if (manufacturingStarted(sheet)) throw new AppError(\'CONFLICT\', MANUFACTURING_STARTED_REVERSAL_MESSAGE)')
  })
  it('uses a permission-gated own-module permit confirmation with authoritative token and retry protection', () => {
    expect(permits).toContain("'production', 'reverseRelease'")
    expect(permits).toContain("can(P.releases.reverse) && row.status === 'active'")
    expect(permits).toContain('window.confirm')
    expect(permits).toContain('expectedToken: row.reversalToken')
    expect(permits).toContain('disabled={reversingId !== undefined}')
    expect(permits).toContain('بما فيها المعكوسة')
  })
  it('reuses the normal invoice editor and approval action, preserving identity and locked posted initial money', () => {
    expect(invoice).toContain('can(P.orders.unapproveInvoice)')
    expect(invoice).toContain("'finalInvoices', 'unapprove'")
    expect(invoice).toContain('expectedRevision: row.approvalRevision')
    expect(invoice).toContain('await startEdit')
    expect(invoice).toContain('إعادة الاعتماد وتحديث نفس الطلب')
    expect(invoice).toContain('الدفعة الأولية المسجّلة سابقاً')
    expect(invoice).toContain('disabled={Boolean(editingOrderId)}')
    expect(invoice).toContain('existingPaidMinor')
    expect(invoice).toContain('لا تُكرّر عند إعادة الاعتماد')
    expect(invoice).toContain('دون تكرار دفعاته')
  })
  it('restores stage actions from backend workflow facts and retains legitimate address/notes editing', () => {
    expect(detail).toContain('detail.data!.workflow.manufacturingIssued')
    expect(detail).toContain('detail.data!.workflow.releaseIssued')
    expect(detail).toContain('detail.data!.workflow.requiredCompletion')
    expect(detail).toContain('تعديل بيانات الطلب')
    expect(detail).toContain('إلغاء الاعتماد')
    expect(detail).toContain('awaiting_approval')
    expect(detail).toContain('!order.archivedAt')
    expect(sheet).toContain('data.historicalLines')
  })
  it('defaults to active orders and applies archive, search and bounded pagination server-side', () => {
    expect(orders).toContain('useState(false)')
    expect(orders).toContain('الطلبات النشطة')
    expect(orders).toContain('الطلبات المؤرشفة')
    expect(orders).toContain("usePagedQuery<Order>('orders', 'list', {")
    expect(orders).toContain('}, { limit: pageSize })')
    expect(orders).not.toContain('offset')
    expect(orders).toContain('const pageSize = 50')
    expect(orders).toContain('can(P.orders.archive)')
    expect(orders).toContain('أرشفة الطلب')
    expect(orders).toContain('استعادة الطلب')
    expect(orders).toContain("archived ? 'restore' : 'archive'")
    // Filter changes restart traversal inside usePagedQuery; Pager renders previous/next.
    expect(orders).toContain('<Pager')
    const selector = source('components/orders/SearchableOrderSelect.tsx')
    expect(selector).toContain('includeArchived: true }, { limit: 50,')
    expect(selector).toContain("'orders', 'get'")
    expect(source('pages/purchases/PurchasesPage.tsx')).toContain('serverSearch')
    expect(source('pages/expenses/ExpensesPage.tsx')).toContain('serverSearch')
  })
  it('preserves Delivery/Installation undo and excludes archived/unapproved orders using authoritative permits', () => {
    expect(delivery).toContain('can(P.deliveries.deleteOrReverse)')
    expect(delivery).toContain("'production', 'cancelDelivery'")
    // DB-10: eligibility is filtered in main, not over an unbounded permit list.
    expect(delivery).toContain('awaitingCompletion: true')
    const production = source('../main/services/production/production.service.ts')
    expect(production).toContain("if (!normalized.includeReversed || normalized.awaitingCompletion) clauses.push(eq(releases.status, 'active'))")
    expect(production).toContain("${orders.archivedAt} IS NULL AND ${orders.status} NOT IN ('cancelled', 'awaiting_approval')")
    expect(delivery).not.toContain('orders.data?.find')
  })
})
